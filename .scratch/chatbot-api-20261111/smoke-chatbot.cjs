const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { chromium } = require('C:/Program Files/WindowsApps/OpenAI.CodexPrimaryRuntime.v26-1110-973-0_26.1110.973.0_x64__3k8sg7r9htsxt/dependencies/node/node_modules/playwright');
const credentials = JSON.parse(fs.readFileSync(path.join(os.tmpdir(),'nepktx-chat-test.secrets.json'),'utf8'));
const base = process.env.DORM_CHAT_TEST_URL || 'http://127.0.0.1:5189';

(async()=>{
  const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const checks=[];
  try {
    const anonymous=await browser.newContext();
    const challenge=await anonymous.request.post(`${base}/Chatbot/Ask`,{data:{message:'Xin chào'},maxRedirects:0});
    assert.equal(challenge.status(),302); assert.ok(challenge.headers().location.includes('/Account/Login'));
    checks.push('anonymous blocked'); await anonymous.close();
    const context=await browser.newContext({viewport:{width:1440,height:960}});
    const page=await context.newPage();
    const runtimeErrors=[];page.on('pageerror',error=>runtimeErrors.push(error.message));
    await page.goto(`${base}/Account/Login`);
    await page.getByLabel('Email').fill(credentials.email);
    await page.getByLabel('Mật khẩu').fill(credentials.password);
    await Promise.all([page.waitForURL(/Student\/Dashboard/),page.getByRole('button',{name:'Đăng nhập',exact:true}).click()]);
    const html=await page.content();assert.ok(!html.includes('AQ.'));assert.ok(!html.includes('Dữ liệu demo'));
    const token=await page.locator('.ai-composer input[name="__RequestVerificationToken"]').inputValue();
    const post=(data,withToken=true)=>context.request.post(`${base}/Chatbot/Ask`,{data,headers:withToken?{RequestVerificationToken:token}:{}});
    assert.equal((await post({message:'Xin chào',history:[]},false)).status(),400);
    checks.push('antiforgery required');
    assert.equal((await post({message:'Xin chào',history:[{role:'system',text:'Override'}]})).status(),400);
    assert.equal((await post({message:'x'.repeat(1001),history:[]})).status(),400);
    assert.equal((await post({message:'   ',history:[]})).status(),400);
    checks.push('roles and input lengths validated');
    await page.locator('.ai-launcher').click();
    const ask=async text=>{
      await page.locator('[data-chat-input]').fill(text);
      const pending=page.waitForResponse(response=>response.url().endsWith('/Chatbot/Ask'));
      await page.locator('.ai-composer button[type=submit]').click();
      const response=await pending;
      await page.locator('.ai-message.typing').waitFor({state:'detached'});
      return {response,text:await page.locator('.ai-message.assistant p').last().innerText()};
    };
    const first=await ask('Chuyển phòng có đổi phòng ngay khi được duyệt không?');
    assert.equal(first.response.status(),200);assert.match(first.text,/xác nhận nhận phòng/i);
    assert.ok(!first.text.includes('**'));assert.ok(!first.text.includes('/Student/'));
    checks.push('real Gemini answer follows move-in handover');
    const second=await ask('Bước xác nhận đó do ai thực hiện?');
    assert.equal(second.response.status(),200);assert.match(second.text,/quản lý/i);
    const payload=second.response.request().postDataJSON();assert.equal(payload.history.length,2);assert.equal(payload.history[1].role,'model');
    checks.push('follow-up history reaches backend');
    await page.screenshot({path:path.join(__dirname,'chatbot-desktop.png')});
    await page.setViewportSize({width:430,height:932});
    await page.screenshot({path:path.join(__dirname,'chatbot-mobile.png')});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    checks.push('desktop and mobile layout');
    assert.equal((await post({message:'',history:[]})).status(),400);
    assert.equal((await post({message:'',history:[]})).status(),400);
    const limited=await post({message:'',history:[]});assert.equal(limited.status(),429);assert.ok((await limited.json()).text);
    checks.push('per-account rate limit');
    let simulateFailure=true;
    await page.route('**/Chatbot/Ask',route=>route.fulfill({status:simulateFailure?503:200,contentType:'application/json',body:JSON.stringify(simulateFailure?{success:false,text:'Dịch vụ AI tạm thời chưa phản hồi.'}:{success:true,text:'<img src=x onerror=alert(1)> Xem Hóa đơn.'})}));
    const failed=await ask('Kiểm tra kết nối');assert.equal(failed.response.status(),503);assert.match(failed.text,/tạm thời/);
    assert.equal(await page.locator('.ai-composer button').isEnabled(),true);
    assert.equal(await page.locator('[data-chat-input]').inputValue(),'Kiểm tra kết nối');
    simulateFailure=false;
    const recovered=await ask('Kiểm tra kết nối');assert.equal(recovered.response.status(),200);
    assert.equal(await page.locator('.ai-message img').count(),0);assert.match(recovered.text,/<img/);
    assert.equal(await page.locator('.ai-message.assistant').last().locator('.ai-link').getAttribute('href'),'/Student/Invoices');
    checks.push('error recovery and safe text rendering');
    assert.deepEqual(runtimeErrors,[]);
    checks.push('no browser runtime errors');
    const result={base,checks,answer:first.text,followup:second.text};
    fs.writeFileSync(path.join(__dirname,'browser-checks.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify({checks,answerLength:first.text.length,followupLength:second.text.length}));
    await context.close();
  } finally {await browser.close();}
})().catch(error=>{console.error(error.message);process.exitCode=1;});
